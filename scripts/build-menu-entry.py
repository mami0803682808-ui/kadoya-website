#!/usr/bin/env python3
"""Build the Maps menu landing page from the homepage, without a second menu source."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def section(source, section_id):
    start = re.search(r'<section\b[^>]*\bid="' + re.escape(section_id) + r'"[^>]*>', source)
    if not start:
        raise ValueError(f'Missing menu source section: {section_id}')
    depth = 0
    for token in re.finditer(r'</?section\b[^>]*>', source[start.start():]):
        depth += -1 if token[0].startswith('</') else 1
        if depth == 0:
            return source[start.start():start.start() + token.end()]
    raise ValueError(f'Unclosed source section: {section_id}')


def build(source):
    menu = section(source, 'menu')
    morning = section(source, 'morning-menu')
    # Root-relative assets work on /menu/ while fragment links stay on this page.
    content = re.sub(r'\b(src|href|poster)="(?![/#]|https?:|tel:|data:)([^"]+)"', r'\1="/\2"', menu + '\n' + morning)
    content = re.sub(r'srcset="([^"]+)"', lambda m: 'srcset="' + ', '.join('/' + x.strip() if not x.strip().startswith(('/', 'https:')) else x.strip() for x in m[1].split(',')) + '"', content)
    # Read source versions rather than maintaining separate CSS/JS version numbers.
    css = re.search(r'<link rel="stylesheet" href="([^"]+)"', source)[1]
    js = re.search(r'<script defer src="(script\.js[^"]*)"', source)[1]
    return f'''<!doctype html>
<!-- Generated by scripts/build-menu-entry.py from index.html. Do not edit menu text here. -->
<html lang="ja" class="kadoya-menu opening-copy-visible"><head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<base href="/">
<meta name="theme-color" content="#f4f0e6">
<title>お品書き｜角屋・小牧市</title>
<meta name="description" content="角屋のお品書き。きしめん・味噌煮込みきしめん・定食・季節の料理・モーニングの写真と税込価格をご覧いただけます。">
<link rel="canonical" href="https://komaki-kadoya.com/menu/">
<meta property="og:title" content="お品書き｜角屋"><meta property="og:type" content="website">
<meta property="og:url" content="https://komaki-kadoya.com/menu/">
<meta property="og:image" content="https://komaki-kadoya.com/images/kadoya-hands.jpg">
<link rel="icon" href="/favicon.png"><link rel="stylesheet" href="/{css}">
<link rel="stylesheet" href="/menu-entry.css?v=20261020-2">
<script defer src="/menu-entry.js?v=20261020"></script>
<script defer src="/{js}"></script></head>
<body class="desktop-rail-ready opening-ready">
<header class="header menu-entry-header">
<a class="menu-home-link" href="/" aria-label="角屋 公式サイトのトップへ"><img src="/images/kadoya-logo.png" alt="角屋" width="2086" height="754"></a>
<button class="menu-btn" aria-label="メニューを開く" aria-controls="menu-entry-nav" aria-expanded="false"><span>店舗案内</span><b aria-hidden="true">☰</b></button>
<nav class="nav" id="menu-entry-nav"><a href="/">公式サイト</a><a href="/#shop">店舗案内</a><a href="/#access">アクセス</a><a href="tel:0568722127">電話で予約</a></nav>
</header>
<main>{content}</main>
<footer><a href="/">角屋 公式サイトへ</a><p>© KADOYA. All Rights Reserved.</p></footer>
</body></html>
'''


if __name__ == '__main__':
    output = build((ROOT / 'index.html').read_text(encoding='utf-8'))
    target = ROOT / 'menu' / 'index.html'
    target.parent.mkdir(exist_ok=True)
    target.write_text(output, encoding='utf-8')
    print('Generated /menu/ from the current homepage menu and morning sections.')
